package com.adient.firewall.repository;

import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.support.GeneratedKeyHolder;
import org.springframework.jdbc.support.KeyHolder;
import org.springframework.stereotype.Repository;

import jakarta.annotation.PostConstruct;
import java.sql.PreparedStatement;
import java.util.*;

@Repository
@RequiredArgsConstructor
@Slf4j
public class DeliberaFormsRepository {

    private final JdbcTemplate db;

    // ─── Init tables ──────────────────────────────────────────────────────────

    @PostConstruct
    public void ensureTables() {
        ensureTable("DELIBERA_FORM_DEMARRAGE");
        ensureTable("DELIBERA_FORM_POKAYOKE");
        ensureTable("DELIBERA_FORM_OK1ERE");
    }

    private void ensureTable(String name) {
        try {
            db.queryForObject("SELECT COUNT(*) FROM SYSTEM." + name + " WHERE ROWNUM=1", Integer.class);
        } catch (Exception e) {
            try {
                db.execute(
                    "CREATE TABLE SYSTEM." + name + " (" +
                    "  ID         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY," +
                    "  PROJET     VARCHAR2(100)," +
                    "  EQUIPE     VARCHAR2(10)," +
                    "  LIGNE      VARCHAR2(20)," +
                    "  FORM_DATA  CLOB," +
                    "  FILLED_BY  VARCHAR2(100)," +
                    "  CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP," +
                    "  UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP" +
                    ")"
                );
                log.info("Created table SYSTEM.{}", name);
            } catch (Exception ex) {
                log.error("Could not create SYSTEM.{}: {}", name, ex.getMessage());
            }
        }
    }

    // ─── Generic helpers ──────────────────────────────────────────────────────

    private String tableName(String type) {
        return switch (type) {
            case "demarrage" -> "DELIBERA_FORM_DEMARRAGE";
            case "pokayoke"  -> "DELIBERA_FORM_POKAYOKE";
            case "ok1ere"    -> "DELIBERA_FORM_OK1ERE";
            default -> throw new IllegalArgumentException("Unknown form type: " + type);
        };
    }

    // ─── List ─────────────────────────────────────────────────────────────────

    public List<Map<String, Object>> listForms(String type, String projet, String equipe,
                                                String ligne, String dateFrom, String dateTo,
                                                int page, int limit) {
        String tbl = tableName(type);
        StringBuilder sql = new StringBuilder(
            "SELECT ID, PROJET, EQUIPE, LIGNE, FILLED_BY, " +
            "TO_CHAR(CREATED_AT,'YYYY-MM-DD HH24:MI:SS') AS CREATED_AT " +
            "FROM SYSTEM." + tbl + " WHERE 1=1 ");
        List<Object> params = new ArrayList<>();

        if (projet != null && !projet.isBlank()) { sql.append("AND UPPER(PROJET)=UPPER(?) "); params.add(projet); }
        if (equipe  != null && !equipe.isBlank())  { sql.append("AND UPPER(EQUIPE)=UPPER(?) ");  params.add(equipe); }
        if (ligne   != null && !ligne.isBlank())   { sql.append("AND UPPER(LIGNE)=UPPER(?) ");   params.add(ligne); }
        if (dateFrom != null && !dateFrom.isBlank()) {
            sql.append("AND TRUNC(CREATED_AT) >= TO_DATE(?,'YYYY-MM-DD') "); params.add(dateFrom);
        }
        if (dateTo != null && !dateTo.isBlank()) {
            sql.append("AND TRUNC(CREATED_AT) <= TO_DATE(?,'YYYY-MM-DD') "); params.add(dateTo);
        }
        sql.append("ORDER BY CREATED_AT DESC ");
        int offset = (page - 1) * limit;
        sql.append("OFFSET ? ROWS FETCH NEXT ? ROWS ONLY");
        params.add(offset);
        params.add(limit);

        return db.queryForList(sql.toString(), params.toArray());
    }

    public int countForms(String type, String projet, String equipe, String ligne,
                          String dateFrom, String dateTo) {
        String tbl = tableName(type);
        StringBuilder sql = new StringBuilder("SELECT COUNT(*) FROM SYSTEM." + tbl + " WHERE 1=1 ");
        List<Object> params = new ArrayList<>();

        if (projet != null && !projet.isBlank()) { sql.append("AND UPPER(PROJET)=UPPER(?) "); params.add(projet); }
        if (equipe  != null && !equipe.isBlank())  { sql.append("AND UPPER(EQUIPE)=UPPER(?) ");  params.add(equipe); }
        if (ligne   != null && !ligne.isBlank())   { sql.append("AND UPPER(LIGNE)=UPPER(?) ");   params.add(ligne); }
        if (dateFrom != null && !dateFrom.isBlank()) {
            sql.append("AND TRUNC(CREATED_AT) >= TO_DATE(?,'YYYY-MM-DD') "); params.add(dateFrom);
        }
        if (dateTo != null && !dateTo.isBlank()) {
            sql.append("AND TRUNC(CREATED_AT) <= TO_DATE(?,'YYYY-MM-DD') "); params.add(dateTo);
        }
        Integer cnt = db.queryForObject(sql.toString(), Integer.class, params.toArray());
        return cnt != null ? cnt : 0;
    }

    // ─── Get by ID ────────────────────────────────────────────────────────────

    public Optional<Map<String, Object>> findById(String type, long id) {
        String tbl = tableName(type);
        List<Map<String, Object>> rows = db.queryForList(
            "SELECT ID, PROJET, EQUIPE, LIGNE, FORM_DATA, FILLED_BY, " +
            "TO_CHAR(CREATED_AT,'YYYY-MM-DD HH24:MI:SS') AS CREATED_AT, " +
            "TO_CHAR(UPDATED_AT,'YYYY-MM-DD HH24:MI:SS') AS UPDATED_AT " +
            "FROM SYSTEM." + tbl + " WHERE ID=?", id);
        return rows.isEmpty() ? Optional.empty() : Optional.of(rows.get(0));
    }

    // ─── Insert ───────────────────────────────────────────────────────────────

    public long insertForm(String type, String projet, String equipe, String ligne,
                           String formData, String filledBy) {
        String tbl = tableName(type);
        KeyHolder kh = new GeneratedKeyHolder();
        db.update(con -> {
            PreparedStatement ps = con.prepareStatement(
                "INSERT INTO SYSTEM." + tbl +
                " (PROJET, EQUIPE, LIGNE, FORM_DATA, FILLED_BY) VALUES (?,?,?,?,?)",
                new String[]{"ID"});
            ps.setString(1, projet);
            ps.setString(2, equipe);
            ps.setString(3, ligne);
            ps.setString(4, formData);
            ps.setString(5, filledBy);
            return ps;
        }, kh);
        return Objects.requireNonNull(kh.getKey()).longValue();
    }

    // ─── Update ───────────────────────────────────────────────────────────────

    public void updateForm(String type, long id, String projet, String equipe, String ligne,
                           String formData) {
        String tbl = tableName(type);
        db.update(
            "UPDATE SYSTEM." + tbl +
            " SET PROJET=?, EQUIPE=?, LIGNE=?, FORM_DATA=?, UPDATED_AT=SYSTIMESTAMP WHERE ID=?",
            projet, equipe, ligne, formData, id);
    }

    // ─── Delete ───────────────────────────────────────────────────────────────

    public void deleteForm(String type, long id) {
        String tbl = tableName(type);
        db.update("DELETE FROM SYSTEM." + tbl + " WHERE ID=?", id);
    }
}
