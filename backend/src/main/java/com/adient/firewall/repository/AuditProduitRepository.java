package com.adient.firewall.repository;

import jakarta.annotation.PostConstruct;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.support.GeneratedKeyHolder;
import org.springframework.jdbc.support.KeyHolder;
import org.springframework.stereotype.Repository;

import java.sql.PreparedStatement;
import java.util.*;

@Repository
@RequiredArgsConstructor
@Slf4j
public class AuditProduitRepository {

    private final JdbcTemplate db;
    private final QualityRepository qRepo;

    @PostConstruct
    public void ensureTables() {
        // Auto-register module in ROLE_PERMISSIONS so it appears in admin UI
        qRepo.seedModulePermissions("audit_produit", "admin", "write", "write", "read");
        try {
            db.queryForObject("SELECT COUNT(*) FROM SYSTEM.AUDIT_PRODUIT WHERE ROWNUM=1", Integer.class);
        } catch (Exception e) {
            try {
                db.execute(
                    "CREATE TABLE SYSTEM.AUDIT_PRODUIT (" +
                    "  ID            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY," +
                    "  PROJET        VARCHAR2(100)," +
                    "  SEMAINE       VARCHAR2(20)," +
                    "  DATE_AUDIT    DATE," +
                    "  AUDITEUR      VARCHAR2(200)," +
                    "  PN            VARCHAR2(100)," +
                    "  DR            VARCHAR2(100)," +
                    "  PRODUIT_AUDITE VARCHAR2(200)," +
                    "  OBJET         VARCHAR2(50)," +
                    "  FORM_DATA     CLOB," +
                    "  RESULTAT      VARCHAR2(10)," +
                    "  STATUS        VARCHAR2(20) DEFAULT 'PENDING'," +
                    "  FILLED_BY     VARCHAR2(100)," +
                    "  VERIFIED_BY   VARCHAR2(100)," +
                    "  VERIFIED_AT   TIMESTAMP," +
                    "  VERIF_COMMENT VARCHAR2(500)," +
                    "  CREATED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP," +
                    "  UPDATED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP" +
                    ")"
                );
                log.info("Created SYSTEM.AUDIT_PRODUIT table");
            } catch (Exception ex) {
                log.error("Could not create AUDIT_PRODUIT table: {}", ex.getMessage());
            }
        }
    }

    // ─── Distinct project names used in audits ────────────────────────────────

    public List<String> getDistinctProjets() {
        try {
            return db.queryForList(
                "SELECT DISTINCT PROJET FROM SYSTEM.AUDIT_PRODUIT WHERE PROJET IS NOT NULL ORDER BY PROJET",
                String.class);
        } catch (Exception e) {
            return new java.util.ArrayList<>();
        }
    }

    // ─── List ─────────────────────────────────────────────────────────────────

    public List<Map<String, Object>> list(String projet, String dateFrom, String dateTo,
                                          String resultat, String status, int page, int limit) {
        int offset = (page - 1) * limit;
        StringBuilder sql = new StringBuilder(
            "SELECT ID, PROJET, SEMAINE, TO_CHAR(DATE_AUDIT,'YYYY-MM-DD') AS DATE_AUDIT," +
            " AUDITEUR, PN, DR, PRODUIT_AUDITE, OBJET, RESULTAT, STATUS, FILLED_BY," +
            " TO_CHAR(CREATED_AT,'YYYY-MM-DD HH24:MI:SS') AS CREATED_AT" +
            " FROM SYSTEM.AUDIT_PRODUIT WHERE 1=1 ");
        List<Object> params = new ArrayList<>();
        appendFilters(sql, params, projet, dateFrom, dateTo, resultat, status);
        sql.append(" ORDER BY CREATED_AT DESC OFFSET ? ROWS FETCH NEXT ? ROWS ONLY");
        params.add(offset);
        params.add(limit);
        return db.queryForList(sql.toString(), params.toArray());
    }

    public int count(String projet, String dateFrom, String dateTo, String resultat, String status) {
        StringBuilder sql = new StringBuilder("SELECT COUNT(*) FROM SYSTEM.AUDIT_PRODUIT WHERE 1=1 ");
        List<Object> params = new ArrayList<>();
        appendFilters(sql, params, projet, dateFrom, dateTo, resultat, status);
        Integer c = db.queryForObject(sql.toString(), Integer.class, params.toArray());
        return c != null ? c : 0;
    }

    private void appendFilters(StringBuilder sql, List<Object> params,
                                String projet, String dateFrom, String dateTo,
                                String resultat, String status) {
        if (projet   != null && !projet.isBlank())   { sql.append("AND UPPER(PROJET)=UPPER(?) "); params.add(projet); }
        if (dateFrom != null && !dateFrom.isBlank()) { sql.append("AND TRUNC(DATE_AUDIT) >= TO_DATE(?,'YYYY-MM-DD') "); params.add(dateFrom); }
        if (dateTo   != null && !dateTo.isBlank())   { sql.append("AND TRUNC(DATE_AUDIT) <= TO_DATE(?,'YYYY-MM-DD') "); params.add(dateTo); }
        if (resultat != null && !resultat.isBlank()) { sql.append("AND UPPER(RESULTAT)=UPPER(?) "); params.add(resultat); }
        if (status   != null && !status.isBlank())   { sql.append("AND UPPER(STATUS)=UPPER(?) "); params.add(status); }
    }

    // ─── Find by ID ───────────────────────────────────────────────────────────

    public Optional<Map<String, Object>> findById(Long id) {
        try {
            Map<String, Object> row = db.queryForMap(
                "SELECT ID, PROJET, SEMAINE, TO_CHAR(DATE_AUDIT,'YYYY-MM-DD') AS DATE_AUDIT," +
                " AUDITEUR, PN, DR, PRODUIT_AUDITE, OBJET, FORM_DATA, RESULTAT, STATUS, FILLED_BY," +
                " VERIFIED_BY, TO_CHAR(VERIFIED_AT,'YYYY-MM-DD HH24:MI:SS') AS VERIFIED_AT, VERIF_COMMENT," +
                " TO_CHAR(CREATED_AT,'YYYY-MM-DD HH24:MI:SS') AS CREATED_AT" +
                " FROM SYSTEM.AUDIT_PRODUIT WHERE ID=?", id);
            return Optional.of(row);
        } catch (Exception e) {
            return Optional.empty();
        }
    }

    // ─── Insert ───────────────────────────────────────────────────────────────

    public long insert(String projet, String semaine, String dateAudit, String auditeur,
                       String pn, String dr, String produitAudite, String objet,
                       String formData, String resultat, String filledBy) {
        KeyHolder kh = new GeneratedKeyHolder();
        db.update(con -> {
            PreparedStatement ps = con.prepareStatement(
                "INSERT INTO SYSTEM.AUDIT_PRODUIT" +
                " (PROJET,SEMAINE,DATE_AUDIT,AUDITEUR,PN,DR,PRODUIT_AUDITE,OBJET,FORM_DATA,RESULTAT,STATUS,FILLED_BY)" +
                " VALUES (?,?,TO_DATE(?,'YYYY-MM-DD'),?,?,?,?,?,?,?,'PENDING',?)",
                new String[]{"ID"}
            );
            ps.setString(1, projet);
            ps.setString(2, semaine);
            ps.setString(3, dateAudit);
            ps.setString(4, auditeur);
            ps.setString(5, pn);
            ps.setString(6, dr);
            ps.setString(7, produitAudite);
            ps.setString(8, objet);
            ps.setString(9, formData);
            ps.setString(10, resultat);
            ps.setString(11, filledBy);
            return ps;
        }, kh);
        return kh.getKey().longValue();
    }

    // ─── Update ───────────────────────────────────────────────────────────────

    public void update(Long id, String projet, String semaine, String dateAudit, String auditeur,
                       String pn, String dr, String produitAudite, String objet,
                       String formData, String resultat) {
        db.update(
            "UPDATE SYSTEM.AUDIT_PRODUIT SET PROJET=?,SEMAINE=?,DATE_AUDIT=TO_DATE(?,'YYYY-MM-DD')," +
            "AUDITEUR=?,PN=?,DR=?,PRODUIT_AUDITE=?,OBJET=?,FORM_DATA=?,RESULTAT=?,STATUS='PENDING'," +
            "UPDATED_AT=SYSTIMESTAMP WHERE ID=?",
            projet, semaine, dateAudit, auditeur, pn, dr, produitAudite, objet, formData, resultat, id);
    }

    // ─── Delete ───────────────────────────────────────────────────────────────

    public void delete(Long id) {
        db.update("DELETE FROM SYSTEM.AUDIT_PRODUIT WHERE ID=?", id);
    }

    // ─── Verify (validate / reject) ───────────────────────────────────────────

    public void verify(Long id, String status, String verifiedBy, String comment) {
        db.update(
            "UPDATE SYSTEM.AUDIT_PRODUIT SET STATUS=?,VERIFIED_BY=?,VERIFIED_AT=SYSTIMESTAMP,VERIF_COMMENT=?," +
            "UPDATED_AT=SYSTIMESTAMP WHERE ID=?",
            status, verifiedBy, comment, id);
    }
}
