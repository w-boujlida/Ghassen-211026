package com.adient.firewall.repository;

import jakarta.annotation.PostConstruct;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.support.GeneratedKeyHolder;
import org.springframework.jdbc.support.KeyHolder;
import org.springframework.stereotype.Repository;

import java.sql.PreparedStatement;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;

@Repository
@RequiredArgsConstructor
@Slf4j
public class NotificationRepository {

    private final JdbcTemplate db;

    @PostConstruct
    public void ensureTables() {
        ensureNotificationsTable();
        ensureNotifReadsTable();
        // Colonne d'idempotence pour les notifications générées automatiquement (ex. dépassement
        // de target) — évite de renotifier en boucle pour la même clé (projet/ligne/heure/date).
        try { db.execute("ALTER TABLE SYSTEM.NOTIFICATIONS ADD DEDUPE_KEY VARCHAR2(300)"); }
        catch (Exception ignored) {}
        // Index unique (NULL autorisés en plusieurs exemplaires sous Oracle) : garantit qu'un
        // dépassement donné ne peut pas être inséré deux fois même en cas d'appels concurrents.
        try { db.execute("CREATE UNIQUE INDEX SYSTEM.UX_NOTIF_DEDUPE_KEY ON SYSTEM.NOTIFICATIONS (DEDUPE_KEY)"); }
        catch (Exception ignored) {}
    }

    private void ensureNotificationsTable() {
        try {
            db.queryForObject("SELECT COUNT(*) FROM SYSTEM.NOTIFICATIONS WHERE ROWNUM=1", Integer.class);
        } catch (Exception e) {
            try {
                db.execute(
                    "CREATE TABLE SYSTEM.NOTIFICATIONS (" +
                    "  ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY," +
                    "  TYPE         VARCHAR2(50) DEFAULT 'audit_produit'," +
                    "  FORM_TYPE    VARCHAR2(50)," +
                    "  FORM_ID      NUMBER," +
                    "  PROJET       VARCHAR2(100)," +
                    "  MESSAGE      VARCHAR2(500)," +
                    "  SENT_BY      VARCHAR2(100)," +
                    "  SENT_AT      TIMESTAMP DEFAULT SYSTIMESTAMP," +
                    "  TARGET_ROLES VARCHAR2(200)" +
                    ")"
                );
                log.info("Created SYSTEM.NOTIFICATIONS table");
            } catch (Exception ex) {
                log.error("Could not create NOTIFICATIONS table: {}", ex.getMessage());
            }
        }
    }

    private void ensureNotifReadsTable() {
        try {
            db.queryForObject("SELECT COUNT(*) FROM SYSTEM.NOTIF_READS WHERE ROWNUM=1", Integer.class);
        } catch (Exception e) {
            try {
                db.execute(
                    "CREATE TABLE SYSTEM.NOTIF_READS (" +
                    "  ID             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY," +
                    "  NOTIF_ID       NUMBER NOT NULL," +
                    "  USER_MATRICULE VARCHAR2(100) NOT NULL," +
                    "  READ_AT        TIMESTAMP," +
                    "  ACTION         VARCHAR2(20)," +
                    "  COMMENT_TEXT   VARCHAR2(500)," +
                    "  ACTED_AT       TIMESTAMP" +
                    ")"
                );
                log.info("Created SYSTEM.NOTIF_READS table");
            } catch (Exception ex) {
                log.error("Could not create NOTIF_READS table: {}", ex.getMessage());
            }
        }
    }

    // ─── Create notification ───────────────────────────────────────────────────

    public long insert(String type, String formType, Long formId, String projet,
                       String message, String sentBy, String targetRoles) {
        KeyHolder kh = new GeneratedKeyHolder();
        db.update(con -> {
            PreparedStatement ps = con.prepareStatement(
                "INSERT INTO SYSTEM.NOTIFICATIONS (TYPE,FORM_TYPE,FORM_ID,PROJET,MESSAGE,SENT_BY,TARGET_ROLES)" +
                " VALUES (?,?,?,?,?,?,?)",
                new String[]{"ID"}
            );
            ps.setString(1, type);
            ps.setString(2, formType);
            if (formId != null) ps.setLong(3, formId); else ps.setNull(3, java.sql.Types.NUMERIC);
            ps.setString(4, projet);
            ps.setString(5, message);
            ps.setString(6, sentBy);
            ps.setString(7, targetRoles);
            return ps;
        }, kh);
        return kh.getKey().longValue();
    }

    // ─── Create notification (idempotent via DEDUPE_KEY) ──────────────────────

    /**
     * Insère la notification seulement si aucune n'existe déjà avec la même DEDUPE_KEY.
     * Utilisé par le dashboard Suivi Qualité pour éviter de renotifier en boucle un même
     * dépassement (clé = projet|ligne|date|créneau horaire). Retourne true si une notification
     * a effectivement été créée.
     */
    public boolean insertIfNotExists(String type, String formType, Long formId, String projet,
                                     String message, String sentBy, String targetRoles, String dedupeKey) {
        Integer existing = db.queryForObject(
            "SELECT COUNT(*) FROM SYSTEM.NOTIFICATIONS WHERE DEDUPE_KEY=?", Integer.class, dedupeKey);
        if (existing != null && existing > 0) return false;

        try {
            db.update(con -> {
                PreparedStatement ps = con.prepareStatement(
                    "INSERT INTO SYSTEM.NOTIFICATIONS (TYPE,FORM_TYPE,FORM_ID,PROJET,MESSAGE,SENT_BY,TARGET_ROLES,DEDUPE_KEY)" +
                    " VALUES (?,?,?,?,?,?,?,?)");
                ps.setString(1, type);
                ps.setString(2, formType);
                if (formId != null) ps.setLong(3, formId); else ps.setNull(3, java.sql.Types.NUMERIC);
                ps.setString(4, projet);
                ps.setString(5, message);
                ps.setString(6, sentBy);
                ps.setString(7, targetRoles);
                ps.setString(8, dedupeKey);
                return ps;
            });
            return true;
        } catch (org.springframework.dao.DuplicateKeyException e) {
            // Deux requêtes concurrentes ont détecté le même dépassement en même temps — la
            // contrainte unique sur DEDUPE_KEY a bloqué le doublon, ce n'est pas une erreur.
            return false;
        }
    }

    // ─── List notifications for a role ────────────────────────────────────────

    public List<Map<String, Object>> listForRole(String role, String matricule, int page, int limit) {
        int offset = (page - 1) * limit;
        String sql =
            "SELECT n.ID, n.TYPE, n.FORM_TYPE, n.FORM_ID, n.PROJET, n.MESSAGE, n.SENT_BY," +
            "  TO_CHAR(n.SENT_AT,'YYYY-MM-DD HH24:MI:SS') AS SENT_AT," +
            "  r.READ_AT, r.ACTION, r.COMMENT_TEXT" +
            " FROM SYSTEM.NOTIFICATIONS n" +
            " LEFT JOIN SYSTEM.NOTIF_READS r ON r.NOTIF_ID = n.ID AND r.USER_MATRICULE = ?" +
            " WHERE (n.TARGET_ROLES LIKE '%' || ? || '%' OR n.SENT_BY = ?)" +
            " ORDER BY n.SENT_AT DESC" +
            " OFFSET ? ROWS FETCH NEXT ? ROWS ONLY";
        return db.queryForList(sql, matricule, role, matricule, offset, limit);
    }

    public int countForRole(String role, String matricule) {
        String sql =
            "SELECT COUNT(*) FROM SYSTEM.NOTIFICATIONS n" +
            " WHERE (n.TARGET_ROLES LIKE '%' || ? || '%' OR n.SENT_BY = ?)";
        Integer c = db.queryForObject(sql, Integer.class, role, matricule);
        return c != null ? c : 0;
    }

    public int countUnread(String role, String matricule) {
        String sql =
            "SELECT COUNT(*) FROM SYSTEM.NOTIFICATIONS n" +
            " WHERE (n.TARGET_ROLES LIKE '%' || ? || '%' OR n.SENT_BY = ?)" +
            " AND NOT EXISTS (SELECT 1 FROM SYSTEM.NOTIF_READS r WHERE r.NOTIF_ID=n.ID AND r.USER_MATRICULE=?)";
        Integer c = db.queryForObject(sql, Integer.class, role, matricule, matricule);
        return c != null ? c : 0;
    }

    // ─── Mark as read ─────────────────────────────────────────────────────────

    public void markRead(Long notifId, String matricule) {
        int existing = db.queryForObject(
            "SELECT COUNT(*) FROM SYSTEM.NOTIF_READS WHERE NOTIF_ID=? AND USER_MATRICULE=?",
            Integer.class, notifId, matricule);
        if (existing == 0) {
            db.update(
                "INSERT INTO SYSTEM.NOTIF_READS (NOTIF_ID, USER_MATRICULE, READ_AT) VALUES (?, ?, SYSTIMESTAMP)",
                notifId, matricule);
        }
    }

    // ─── Action (validate / reject) ───────────────────────────────────────────

    public void saveAction(Long notifId, String matricule, String action, String comment) {
        int existing = db.queryForObject(
            "SELECT COUNT(*) FROM SYSTEM.NOTIF_READS WHERE NOTIF_ID=? AND USER_MATRICULE=?",
            Integer.class, notifId, matricule);
        if (existing == 0) {
            db.update(
                "INSERT INTO SYSTEM.NOTIF_READS (NOTIF_ID, USER_MATRICULE, READ_AT, ACTION, COMMENT_TEXT, ACTED_AT)" +
                " VALUES (?, ?, SYSTIMESTAMP, ?, ?, SYSTIMESTAMP)",
                notifId, matricule, action, comment);
        } else {
            db.update(
                "UPDATE SYSTEM.NOTIF_READS SET ACTION=?, COMMENT_TEXT=?, ACTED_AT=SYSTIMESTAMP, READ_AT=COALESCE(READ_AT,SYSTIMESTAMP)" +
                " WHERE NOTIF_ID=? AND USER_MATRICULE=?",
                action, comment, notifId, matricule);
        }
    }

    public Map<String, Object> findById(Long id) {
        try {
            return db.queryForMap(
                "SELECT ID, TYPE, FORM_TYPE, FORM_ID, PROJET, MESSAGE, SENT_BY," +
                " TO_CHAR(SENT_AT,'YYYY-MM-DD HH24:MI:SS') AS SENT_AT, TARGET_ROLES" +
                " FROM SYSTEM.NOTIFICATIONS WHERE ID=?", id);
        } catch (Exception e) {
            return null;
        }
    }
}
